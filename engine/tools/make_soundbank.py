#!/usr/bin/env python3
"""WAV files -> MEXNya sound bank (sound/bank.mcs), played with audio_play(id, ...).

    python3 engine/tools/make_soundbank.py assets/sound/bank.mcs jump.wav coin.wav loop:music.wav

Sound ids are the argument order (0, 1, 2, ...); a `loop:` prefix marks a looping sound.
A header with matching constants is written next to the bank (bank_ids.h) for your code.
Any 8/16-bit PCM WAV, mono or stereo, any rate: it is mixed to mono 16-bit at its own
rate (the engine resamples to 44.1 kHz when it plays).

Layout: "MCS1", u32 count, count x {u32 offset, u32 samples, u32 rate, u32 loops},
then the 16-bit samples.
"""
import os
import re
import struct
import sys
import wave


def read_wav(path):
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width == 1:
        samples = [(b - 128) << 8 for b in raw]
    elif width == 2:
        samples = list(struct.unpack("<%dh" % (len(raw) // 2), raw))
    else:
        sys.exit("make_soundbank: %s: only 8- or 16-bit PCM" % path)
    if ch > 1:
        samples = [sum(samples[i:i + ch]) // ch for i in range(0, len(samples), ch)]
    return samples, rate


def main():
    if len(sys.argv) < 3:
        print(__doc__.strip())
        return 1
    out, inputs = sys.argv[1], sys.argv[2:]
    entries, blobs = [], []
    names = []
    for arg in inputs:
        loops = arg.startswith("loop:")
        path = arg[5:] if loops else arg
        samples, rate = read_wav(path)
        blobs.append(struct.pack("<%dh" % len(samples), *samples))
        entries.append((len(samples), rate, 1 if loops else 0))
        names.append(re.sub(r"[^A-Z0-9]", "_", os.path.splitext(os.path.basename(path))[0].upper()))
    offset = 8 + 16 * len(entries)
    head = struct.pack("<4sI", b"MCS1", len(entries))
    table = b""
    for (n, rate, loops), blob in zip(entries, blobs):
        table += struct.pack("<4I", offset, n, rate, loops)
        offset += len(blob)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "wb") as f:
        f.write(head + table + b"".join(blobs))
    hdr = os.path.join(os.path.dirname(os.path.abspath(out)), "bank_ids.h")
    with open(hdr, "w") as f:
        f.write("// Generated by engine/tools/make_soundbank.py\n#pragma once\nenum {\n")
        for i, n in enumerate(names):
            f.write("    SND_%s = %d,\n" % (n, i))
        f.write("    SND_COUNT = %d\n};\n" % len(names))
    print("make_soundbank: %d sounds -> %s (+ bank_ids.h)" % (len(entries), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
